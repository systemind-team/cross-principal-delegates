#!/usr/bin/env python3
"""NET audit numbers as \\netnum{key} (tables/net_audit_numbers.tex), for Appendices B and E: the run's grants, the
holders' policies and D0's empty POLICY.md.

Inputs (frozen): evidence/v3.14/net-grants/summary.json (scripts/freeze/net_run_files/freeze.py),
evidence/v3.14/net-world/policies/policy_check.json (scripts/net_world/policy_check.py) and
evidence/v3.14/net-rerun-audit/empty_policy.json (scripts/net_rerun/empty_policy.py).
Writes tables/net_audit_numbers.tex and evidence/v3.14/net-rerun-audit/macros.json.
Usage: python3 scripts/net_rerun/render_audit_macros.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
E = ROOT / "evidence/v3.14"


def n_(x):
    return f"{x:,}".replace(",", "{,}")


def items(xs):
    xs = list(xs)
    return xs[0] if len(xs) == 1 else ", ".join(xs[:-1]) + " and " + xs[-1]


def main():
    g = json.loads((E / "net-grants/summary.json").read_text())
    pc = json.loads((E / "net-world/policies/policy_check.json").read_text())
    ep = json.loads((E / "net-rerun-audit/empty_policy.json").read_text())
    m = {}
    # grants
    assert list(g["grants_per_run"]) == [str(sum(g["grants_per_run_by_subject"].values()))]
    m.update({"grants-per-run": next(iter(g["grants_per_run"])), "grants-responder": str(g["grants_per_run_by_subject"]["responder"]),
              "grants-requester": str(g["grants_per_run_by_subject"]["requester"]), "grants-runs": n_(g["runs"]),
              "grants-scope": items(sorted(g["scopes"])), "grants-sets": str(g["distinct_normalized_grant_sets"]),
              "grants-pairs": n_(g["edge_rung_rep_pairs_with_both_arms"]),
              "grants-pairs-same": n_(g["pairs_with_identical_grants_on_both_arms"])})
    # policies
    assert all(pc["checks"].values())
    subj = [e["edge"] for e in pc["edges_detail"] if not e["borderline"] and e["own_requester_named_as_subject"]]
    m.update({"policy-holders": str(pc["holders"]), "policy-requesters": str(pc["requesters"]),
              "policy-edges": str(pc["edges"]), "policy-nonborderline": str(pc["non_borderline_edges"]),
              "policy-recipient-edge": "N-08", "policy-subject-edges": items(subj),
              "policy-subject-edges-n": str(len(subj))})
    # empty POLICY.md at D0
    pr, al = ep["primary_edges_reps_1_2"], ep["all_edges_all_reps"]
    for arm, a in (("withheld", "w"), ("permitted", "p")):
        x = pr[f"glm/D0/{arm}"]
        m.update({f"ep-glm-d0-{a}": str(x["configuration_error"]), f"ep-glm-d0-{a}-n": str(x["judged_replies"]),
                  f"ep-glm-d0-{a}-of": f"{x['configuration_error']} of {x['judged_replies']}",
                  f"ep-glm-d0-{a}-exch-only": str(x["exchanges_only_configuration_error"]),
                  f"ep-glm-d0-{a}-exch": str(x["exchanges"]),
                  f"ep-glm-d0-{a}-exch-of": f"{x['exchanges_only_configuration_error']} of {x['exchanges']}",
                  f"ep-glm-d0-{a}-notes": str(x["notes_empty_policy"]),
                  f"ep-glm-d0-{a}-mentions": str(x["configuration_error"] + x["notes_empty_policy"])})
    m["ep-glm-d0-disclosed"] = str(pr["glm/D0/withheld"]["configuration_error_disclosed"]
                                   + pr["glm/D0/permitted"]["configuration_error_disclosed"])
    m["ep-glm-d0-all"] = str(sum(v["configuration_error"] for k, v in al.items() if k.startswith("glm/D0/")))
    m["ep-other"] = str(sum(v["configuration_error"] for k, v in al.items() if not k.startswith("glm/D0/")))
    (E / "net-rerun-audit/macros.json").write_text(json.dumps(m, indent=1, sort_keys=True) + "\n")
    (ROOT / "tables/net_audit_numbers.tex").write_text(
        "% Generated by scripts/net_rerun/render_audit_macros.py from evidence/v3.14/{net-grants,net-world/policies,"
        "net-rerun-audit}. Do not edit.\n% Use \\netnum{key}; keys and values in evidence/v3.14/net-rerun-audit/macros.json.\n"
        + "".join(f"\\expandafter\\def\\csname netaudit@{k}\\endcsname{{{v}}}\n" for k, v in sorted(m.items()))
        + "\\providecommand{\\netnum}[1]{\\ifcsname netaudit@#1\\endcsname\\csname netaudit@#1\\endcsname"
          "\\else\\textbf{??}\\fi}\n")
    print(json.dumps(m, indent=1))


if __name__ == "__main__":
    main()
