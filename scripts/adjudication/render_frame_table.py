#!/usr/bin/env python3
"""P1-2: render Appendix F's frame and strata table from the committed frame (no number typed by hand).

Reads evidence/v3.14/adjudication/frame/cells.json; writes tables/adjudication_frame.tex.

Usage: python3 render_frame_table.py [--out tables]
"""
import argparse
import json
import os
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
ap = argparse.ArgumentParser()
ap.add_argument("--out", default=str(ROOT / "tables"))
a = ap.parse_args()
c = json.load(open(ROOT / "evidence/v3.14/adjudication/frame/cells.json"))
p2, p1 = c["pair2"], c["pair1"]
n = lambda x: f"{x:,}".replace(",", "{,}")

STRATA2 = [("S1L", "later replies of the 79 later exposures, with a diagnostic exposure"),
           ("S1F", "first replies of the 79 later exposures"),
           ("S2", "first replies with a diagnostic exposure, not recorded as answers"),
           ("S3P", "replies recorded as answers, no diagnostic exposure"),
           ("S4P", "replies recorded as answers, with a diagnostic exposure"),
           ("SR", "replies with an exposure for the scoring matcher only (first, and later where the first reply had none)"),
           ("S5F", "first replies recorded as refusals, no exposure for either matcher"),
           ("S5L", "later replies recorded as refusals, no exposure for either matcher, where the first reply had none")]
rows = []
for k, d in STRATA2:
    v = p2["strata"][k]
    rows.append(f"{k} & {d} & {n(v['population'])} & {'all' if v['draw'] == 'census' else n(v['draw'])} \\\\")
STRATA1 = [("S3I", "answered, no exposure"), ("S4I", "answered, with an exposure (decision leak)"),
           ("S6F", "refused, with an exposure (refusal-channel leak)"), ("S6C", "refused, no exposure")]
for k, d in STRATA1:
    pops = [p1["strata"][f"{k} {m}"] for m in ("DeepSeek", "GLM", "GPT-5.6")]
    rows.append(f"{k} & PAIR~I, {d}; DeepSeek V4.1, GLM-5.3-Flash, GPT-5.6 & {', '.join(n(x['population']) for x in pops)} & "
                f"{', '.join(n(x['draw']) for x in pops)} \\\\")
# Replies outside every stratum (not drawn), and among them the requests that drew no reply, from the frame.
nd = p2["not_drawn"]
f_nr = sum(c["replies"] for c in p2["cells"] if c["position"] == "first" and c["record"] == "no reply")
l_nr = sum(c["replies"] for c in p2["cells"] if c["position"] == "later" and c["record"] == "no reply")
tex = r"""% Generated by scripts/adjudication/render_frame_table.py from evidence/v3.14/adjudication/frame/cells.json.
\begin{table}[!ht]
\centering\small
\caption{\textbf{What the two LLM coders read.} PAIR~II: the probing grid's """ + n(p2["replies"]) + r""" replies to
protected questions (""" + n(p2["first_replies"]) + r""" first, """ + n(p2["replies"] - p2["first_replies"]) + r""" later), cut by
position, the diagnostic matcher's exposure, the scoring matcher's exposure and the requester's record, and drawn by stratum
(all, or a seeded sample). Not drawn: """ + n(nd) + r""" (among them """ + n(f_nr + l_nr) + r""" requests that drew no reply: """ + n(f_nr) + r""" first and """ + n(l_nr) + r""" later), outside every estimate. PAIR~I: scored protected questions per responder model (DeepSeek V4.1, GLM-5.3-Flash, GPT-5.6, the Codex CLI and
requester-swap cells counted under their responder). Rates are weighted by each
stratum's inclusion probability.}
\label{tab:adjudication-frame}
\setlength{\tabcolsep}{3pt}
\begin{tabularx}{\linewidth}{@{}lYrr@{}}
\toprule
Stratum & Replies & Population & Labeled \\
\midrule
""" + "\n".join(rows[:8]) + "\n\\addlinespace[2pt]\n" + "\n".join(rows[8:]) + r"""
\bottomrule
\end{tabularx}
\end{table}
"""
os.makedirs(a.out, exist_ok=True)
open(os.path.join(a.out, "adjudication_frame.tex"), "w").write(tex)
print("wrote", os.path.join(a.out, "adjudication_frame.tex"))
