#!/usr/bin/env python3
"""Mechanism baseline: render the \\mechnum{key} macros the Appendix B paragraph (and the optional body
sentence) cite, from the frozen results.json. No model calls.

Usage: python3 scripts/mechanism_static/render_macros.py > tables/mechanism_numbers.tex
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
d = json.load(open(ROOT / "evidence/v3.14/mechanism-static/results.json"))
nums = {}


def colo(req, g="item"):
    for c in d["colocation"]:
        if c["label_set"] == ("category" if req == "ALL" else "relationship") and c["granularity"] == g and c["requester"] == req:
            return c


def occ(req, rule, loc, g="item"):
    for o in d["occurrence"]:
        if o["label_set"] == ("category" if req == "ALL" else "relationship") and o["rule"] == rule and o["granularity"] == g and o["requester"] == req:
            return o[f"protected_left_readable_{loc}"], o[f"over_block_{loc}"], o["protected"], o["entitled"]


REQS = {"R0": "R0", "R1": "R1", "R2": "R2", "R3": "R3", "ALL": "cat"}
for req, tag in REQS.items():
    c = colo(req)
    nums[f"colo-{tag}-prot-share-protsrc"] = str(c["protected_sharing_resource_with_entitled"])
    nums[f"colo-{tag}-prot-n"] = str(c["protected"])
    nums[f"colo-{tag}-ent-share-protsrc"] = str(c["entitled_sharing_resource_with_protected"])
    nums[f"colo-{tag}-ent-n"] = str(c["entitled"])
    for loc in ("declared", "matcher", "verbatim"):
        pr, ov, pn, en = occ(req, "strict", loc)
        nums[f"occ-{tag}-strict-{loc}-pr"] = str(pr)
        nums[f"occ-{tag}-strict-{loc}-prn"] = str(pn)

f = d["feasibility"]
nums["sep-one"] = str(f["separability"]["items_one_category"])
nums["sep-items"] = str(f["separability"]["items"])
nums["match-nonsource"] = str(f["fact_occurrence"]["questions_with_a_gold_fact_in_a_non_source_resource_matcher"])
nums["match-nonsource-verbatim"] = str(f["fact_occurrence"]["questions_with_a_gold_fact_in_a_non_source_resource_verbatim"])
nums["questions"] = str(f["questions"])
nums["defn-draws"] = str(d["definitional"]["random_label_draws"])
nums["defn-violations"] = str(d["definitional"]["violations_of_strict_100_removed_and_loose_0_overblock"])

lo = {x["requester"]: x for x in d["leave_one_pass_out"]["requesters"]}


def pct(x):
    return f"{round(100 * x, 1)}" if x is not None else "--"


for req, tag in (("R1", "R1"), ("R2", "R2"), ("R3", "R3"), ("R0", "R0")):
    x = lo[req]
    nums[f"lopo-{tag}-strict-read"] = pct(x["mean_strict_protected_readable_share"])
    nums[f"lopo-{tag}-strict-over"] = pct(x["mean_strict_over_block_share"])
    nums[f"lopo-{tag}-loose-read"] = pct(x["mean_loose_protected_readable_share"])
    nums[f"lopo-{tag}-loose-over"] = pct(x["mean_loose_over_block_share"])
    # Per-pass range of the same shares (the mean above averages exactly these five). Units are QUESTIONS: the
    # read share is protected questions left readable / truth-protected questions, the over share is entitled
    # questions over-blocked / truth-entitled questions, per held-out pass; a pass with a zero denominator is skipped.
    for rule in ("strict", "loose"):
        for meas, num, den in (("read", f"{rule}_protected_readable", "truth_protected"),
                               ("over", f"{rule}_over_block", "truth_entitled")):
            shares = [100 * p[num] / p[den] for p in x["per_held_pass"] if p[den]]
            if shares:
                # one decimal, the precision of the means printed beside them
                nums[f"lopo-{tag}-{rule}-{meas}-min"] = f"{round(min(shares), 1)}"
                nums[f"lopo-{tag}-{rule}-{meas}-max"] = f"{round(max(shares), 1)}"

for req in ("R0", "R1", "R2", "R3"):
    a = d["actions"]["per_requester"][req]
    nums[f"act-{req}-exec"] = str(a["execute"])
    nums[f"act-{req}-refuse"] = str(a["refuse"])

def tex_int(v):
    """An integer of 1,000 or more is emitted with LaTeX thousands separators, e.g. 1000 -> 1{,}000."""
    if v.isdigit() and int(v) >= 1000:
        return f"{int(v):,}".replace(",", "{,}")
    return v


nums = {k: tex_int(v) for k, v in nums.items()}
out = "".join(f"\\expandafter\\def\\csname mech@{k}\\endcsname{{{v}}}\n" for k, v in sorted(nums.items()))
out += "\\providecommand{\\mechnum}[1]{\\ifcsname mech@#1\\endcsname\\csname mech@#1\\endcsname\\else\\textbf{??}\\fi}\n"
print("% Generated by scripts/mechanism_static/render_macros.py from evidence/v3.14/mechanism-static/results.json.")
print(out, end="")
