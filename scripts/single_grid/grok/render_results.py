#!/usr/bin/env python3
"""Render evidence/v3.13/single-grid-grok/RESULTS.md from the analysis output and the run evidence.

  python3 scripts/single_grid/grok/render_results.py

Reads grok_supplement.json (analyze.py), run/{plan,retry}/rescore.json, run/retry_list.json,
run/retry_list_merged.json, run/cost-all.json and trial/cost.json. Every number in RESULTS.md comes from
those files.
"""
import collections, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import DESIGN_DIR, MODELS, NEW, POLICIES, REQUESTERS

BASE = os.path.dirname(DESIGN_DIR)
RUN = os.path.join(BASE, "run")
NAME = {"grok": "Grok-4.6", "ds41": "DeepSeek", "glm": "GLM", "luna": "GPT-5.6"}
REQ = {"R0": "R0 stranger", "R1": "R1 colleague", "R2": "R2 CEO's assistant", "R3": "R3 close friend"}


def load(*parts):
    return json.load(open(os.path.join(BASE, *parts)))


o = load("grok_supplement.json")
plan_rep = load("run", "plan", "rescore.json")["cells"]
retry_rep = load("run", "retry", "rescore.json")["cells"]
listed = load("run", "retry_list.json")
merged = load("run", "retry_list_merged.json")
cost = load("run", "cost-all.json")
trial = load("trial", "cost.json")
plan = json.load(open(os.path.join(DESIGN_DIR, "run_plan.json")))


def pct(b, digits=1):
    return "–" if b is None or b.get("pct") is None else f"{b['pct']:.{digits}f}"


def frac(b):
    return "–" if b is None or not b.get("n") else f"{b['pct']:.1f} ({b['k']}/{b['n']})"


def pv(p):
    return f"{p:.2g}" if p >= 0.001 else f"{p:.1e}"


# delivery after the merge
rows, tot = [], collections.Counter()
for cid in plan["cells"]:
    p = plan_rep[cid]["taskCounts"]
    errors = collections.Counter(p["errorCodes"])
    scored = p["scored"] + p["recovery"]["recoveredQa"]
    replaced = merged["cells"].get(cid, [])
    for t in replaced:
        errors[t["errorCode"]] -= 1
    if replaced:
        r = retry_rep[f"{cid}-retry"]["taskCounts"]
        errors.update(r["errorCodes"])
        scored += r["scored"] + r["recovery"]["recoveredQa"]
    left = len(listed["cells"].get(cid, [])) - len(replaced)
    errors = +errors
    rows.append((cid, p["selected"], scored, len(replaced), left, errors))
    tot.update(selected=p["selected"], scored=scored, rerun=len(replaced), left=left)
    tot.update({f"err:{k}": v for k, v in errors.items()})

spend = collections.Counter()
for t in cost["taskRuns"]:
    kind = "retry" if t["run"].endswith("-retry") else "plan"
    spend[kind] += t["usd"]["data_zone"]
    spend[kind + "_global"] += t["usd"]["global"]
trial_usd = sum(t["usd"]["data_zone"] for t in trial["taskRuns"])
trial_global = sum(t["usd"]["global"] for t in trial["taskRuns"])
total = spend["plan"] + spend["retry"] + trial_usd

L = []
w = L.append
w("# PAIR I supplement: grok-4.6 results")
w("")
w("Generated by `scripts/single_grid/grok/render_results.py`. The design is in")
w("`planning/2026-10-05-pair1-grok-supplement.md`; the task lists, the seed and `analyze.py` were committed in")
w("`2925039`, before any grok-4.6 task-run.")
w("")
w("## Run")
w("")
w(f"- **Model:** Azure AI Foundry deployment `grok-4.6` on both sides; every response was served as `grok-4.6`. Temperature 0.")
w("- **Code:** SharedEval runtime `40f4f01`, checkout `5aaa7f1`; SharedOS `3aa07e3`. The workflow is files-single, with category grading at run time and relationship-v2 rescoring offline with recovery.")
w(f"- **Plan:** {plan['taskRuns']:,} task-runs in 12 cells, run 2026-10-06 18:54 to 2026-10-07 03:31 UTC, three cells at a time.")
w(f"- **Rate-limit rerun:** {listed['taskRuns']} task-runs ended in error because Azure kept answering HTTP 429 until the runner's retries ran out (`retry_list.py`), so the model never produced an outcome.")
w(f"  - These ran again, as approved, with the same configs and one cell at a time.")
w(f"  - {merged['taskRuns']} of them ran before the `grok-4.6` deployment stopped responding at about 06:18 UTC on 2026-10-07; read timeouts continued for at least 80 minutes, while GPT-5.6 on the same resource answered normally.")
w(f"  - The other {listed['taskRuns'] - merged['taskRuns']} stay errors.")
w(f"  - Each rerun row replaces its error row only after the rerun's own rescore passes the same gates (`analyze.py --grok-retry`).")
w(f"- **Spend** (Azure Data Zone list price; Azure returns no cost):")
w("")
w("| Item | Data Zone | Global |")
w("| --- | --- | --- |")
w(f"| Plan | ${spend['plan']:.2f} | ${spend['plan_global']:.2f} |")
w(f"| Rerun, including the attempts the outage killed | ${spend['retry']:.2f} | ${spend['retry_global']:.2f} |")
w(f"| Price trial | ${trial_usd:.2f} | ${trial_global:.2f} |")
w(f"| **Total** (approved cap $200) | **${total:.2f}** | ${spend['plan_global'] + spend['retry_global'] + trial_global:.2f} |")
w("")
w("## Delivery")
w("")
w(f"{tot['scored']:,} of {tot['selected']:,} task-runs reached a score ({100 * tot['scored'] / tot['selected']:.1f}%, with recovery).")
w("")
w("| Cell | Planned | Scored | Rerun | Left from 429 | Errors after merge |")
w("| --- | --- | --- | --- | --- | --- |")
for cid, sel, sc, rr, left, errs in rows:
    e = ", ".join(f"{k} {v}" for k, v in sorted(errs.items())) or "–"
    w(f"| {cid} | {sel} | {sc} ({100 * sc / sel:.0f}%) | {rr} | {left} | {e} |")
w("")
w("The remaining errors fall into two groups:")
w("")
w("- The 77 task-runs the outage took, which were first rate-limited and then lost again.")
w("- Requester turns that could not be proven complete (`INDETERMINATE_EXTERNAL_OPERATION`), which the rescore recovers where the ledger allows, plus a few responder or session failures without a 429.")
w("")
w("Tests pair by task and use only tasks scored in both cells.")
w("")

rel = o["random"]["relationship"]
w("## Random set: 100 tasks × 4 requesters (relationship-v2)")
w("")
w("This is the unbiased population. Total leak (TL) counts protected QA items whose reply carries a gold fact,")
w("whether recorded as an answer or inside a refusal. FR counts entitled QA items and authorized actions that")
w("were declined. Each entry is a percentage; n is the number of grok units.")
w("")
w("| Requester | Policy | Grok TL | DeepSeek TL | GLM TL | GPT-5.6 TL | Grok FR | DeepSeek FR | GLM FR | GPT-5.6 FR | n (TL/FR) |")
w("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
for req in REQUESTERS:
    for pol in POLICIES:
        r = {f: rel["rates"][f"{f}-{pol}-{req}"] for f in (NEW,) + MODELS}
        w(f"| {REQ[req]} | {pol} | **{pct(r[NEW]['total_leak'])}** | " + " | ".join(pct(r[f]["total_leak"]) for f in MODELS)
          + f" | **{pct(r[NEW]['fr'])}** | " + " | ".join(pct(r[f]["fr"]) for f in MODELS)
          + f" | {r[NEW]['total_leak']['n']}/{r[NEW]['fr']['n']} |")
w("")
w("R0 is entitled to one QA item, which the random set does not contain, so its FR is undefined.")
w("R3 has 5–6 entitled units, so its FR is not interpretable.")
w("")

w("## Primary tests (preregistered; Holm within each family)")
w("")
for fam, title in (("F1", "F1: grok's own ladder on the random set (relationship-v2, exact McNemar paired by task)"),
                   ("F2", "F2: grok against each model at D2 on the random set"),
                   ("F3", "F3: leave-one-out on the hard set at D2, pooled over requesters")):
    w(f"**{title}**")
    w("")
    if fam == "F1":
        w("| Requester | Step | Metric | n | Before | After | p | Holm p |")
        w("| --- | --- | --- | --- | --- | --- | --- | --- |")
        for t in o["primary"][fam]:
            w(f"| {t['requester']} | {t['from']}→{t['to']} | {t['metric']} | {t['n']} | {t.get('a_pct', 0):.1f} | {t.get('b_pct', 0):.1f} | {pv(t['p'])} | {pv(t['p_holm'])} |")
    else:
        w("| Requester | Model | Metric | Units | Model | Grok | p | Holm p |")
        w("| --- | --- | --- | --- | --- | --- | --- | --- |")
        for t in o["primary"][fam]:
            w(f"| {t['requester']} | {NAME[t['model']]} | {t['metric']} | {t['n']} | {t.get('a_pct', 0):.1f} | {t.get('b_pct', 0):.1f} | {pv(t['p'])} | {pv(t['p_holm'])} |")
    w("")
w("F3 compares grok with model M on the pairs that the other two models made hard. Those pairs were chosen without")
w("looking at M or at grok, so neither side is inflated by the selection.")
w("")

H = o["hard"]["relationship"]
w("## Hard set: 609 pairs (relationship-v2)")
w("")
w("Rates on all 609 pairs, pooled over requesters. The three models' rates here are inflated by selection: the")
w("pairs were chosen for their failures. Only grok's column, and the leave-one-out contrasts below, are fair to read.")
w("")
w("| Policy | Grok TL | DeepSeek TL | GLM TL | GPT-5.6 TL | Grok FR | DeepSeek FR | GLM FR | GPT-5.6 FR |")
w("| --- | --- | --- | --- | --- | --- | --- | --- | --- |")
for pol in POLICIES:
    r = {f: H["rates"][f"{f}-{pol}-all"] for f in (NEW,) + MODELS}
    w(f"| {pol} | **{frac(r[NEW]['total_leak'])}** | " + " | ".join(pct(r[f]["total_leak"]) for f in MODELS)
      + f" | **{frac(r[NEW]['fr'])}** | " + " | ".join(pct(r[f]["fr"]) for f in MODELS) + " |")
w("")
w("**Leave-one-out, D1 and D2, pooled over requesters.** Pairs is the size of the leave-one-out set; units are those")
w("scored and eligible on both sides.")
w("")
w("| Policy | Held-out model | Metric | Pairs | Units | Model | Grok | Model only | Grok only | p |")
w("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
for t in H["leaveOneOut"]:
    if t["requester"] == "all" and t["policy"] in ("D1", "D2") and t["metric"] in ("total_leak", "fr"):
        w(f"| {t['policy']} | {NAME[t['model']]} | {t['metric']} | {t['pairs']} | {t['n']} | {t.get('a_pct', 0):.1f} | {t.get('b_pct', 0):.1f} | {t['a_only']} | {t['b_only']} | {pv(t['p'])} |")
w("")

cat = o["random"]["category"]
w("## Category contract (run-time labels), random set")
w("")
w("| Requester | Policy | Grok leak | DeepSeek leak | GLM leak | GPT-5.6 leak | Grok FR | DeepSeek FR | GLM FR | GPT-5.6 FR |")
w("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
for req in REQUESTERS:
    for pol in POLICIES:
        r = {f: cat["rates"][f"{f}-{pol}-{req}"] for f in (NEW,) + MODELS}
        w(f"| {REQ[req]} | {pol} | {pct(r[NEW]['leak'])} | " + " | ".join(pct(r[f]["leak"]) for f in MODELS)
          + f" | {pct(r[NEW]['fr'])} | " + " | ".join(pct(r[f]["fr"]) for f in MODELS) + " |")
w("")
w("The category contract is requester-independent, so a refusal the relationship labels expect (for example, the")
w("close friend asking for work items) counts as a false refusal here. The table is descriptive.")
w("")

w("## Descriptive")
w("")
r0 = next(t for t in rel["ladder"] if t["requester"] == "R0" and t["from"] == "D0" and t["to"] == "D1" and t["metric"] == "total_leak")
w(f"- **Stranger under generic caution.** Grok's total leak to R0 rises from {r0['a_pct']:.1f}% at D0 to {r0['b_pct']:.1f}% at D1 on the same {r0['n']} protected units.")
w(f"  - The change is {r0['b_only']} up and {r0['a_only']} down (p = {pv(r0['p'])}; not a primary test).")
w("  - D2 brings it back. The paper reports the same D0→D1 rise for DeepSeek.")
for req in ("R1", "R2", "R3"):
    r = {pol: rel["rates"][f"{NEW}-{pol}-{req}"] for pol in POLICIES}
    w(f"- **Grok, {REQ[req]}.**")
    w(f"  - Information utility D0/D1/D2: {pct(r['D0']['iu'])} / {pct(r['D1']['iu'])} / {pct(r['D2']['iu'])}%.")
    w(f"  - Action safety: {pct(r['D0']['as'])} / {pct(r['D1']['as'])} / {pct(r['D2']['as'])}%.")
w("")
w("## Reading")
w("")
f1 = {(t["requester"], t["from"], t["metric"]): t for t in o["primary"]["F1"]}
f3 = {(t["model"], t["metric"]): t for t in o["primary"]["F3"]}
r3 = (f1[("R3", "D0", "total_leak")], f1[("R3", "D1", "total_leak")])
w("1. **Grok-4.6 climbs the same ladder.**")
w(f"   - For the close friend, total leak falls from {r3[0]['a_pct']:.0f}% (D0) to {r3[0]['b_pct']:.0f}% (D1) to {r3[1]['b_pct']:.0f}% (D2). Both steps survive Holm correction.")
w("   - The colleague and the CEO's assistant move the same way. With 19–25 protected units per cell, those steps do not reach significance.")
w("2. **On the random set at D2, grok is not distinguishable from the three PAIR I models** on total leak or false refusal (F2: no test survives Holm).")
w("   - At 100 tasks per requester, F2 can only detect differences of about 20 points or more.")
w("3. **On the hard set, leakage at D2 does not go away with grok.**")
w(f"   - DeepSeek: {f3[('ds41', 'total_leak')]['a_pct']:.1f}% against grok's {f3[('ds41', 'total_leak')]['b_pct']:.1f}% (p = {pv(f3[('ds41', 'total_leak')]['p'])}).")
w(f"   - GPT-5.6: {f3[('luna', 'total_leak')]['a_pct']:.1f}% against {f3[('luna', 'total_leak')]['b_pct']:.1f}% (p = {pv(f3[('luna', 'total_leak')]['p'])}).")
w(f"   - GLM: {f3[('glm', 'total_leak')]['a_pct']:.1f}% against {f3[('glm', 'total_leak')]['b_pct']:.1f}%. This is the one difference that survives Holm.")
w("   - On the pairs two models made hard, grok leaks about as often as the third model does.")
w("4. **D2's false refusals on the hard set are mostly shared.**")
w(f"   - On the entitled items two models refused, grok refuses {f3[('glm', 'fr')]['b_pct']:.0f}–{f3[('ds41', 'fr')]['b_pct']:.0f}%.")
w(f"   - That is fewer than DeepSeek ({f3[('ds41', 'fr')]['a_pct']:.0f}%, Holm p = {pv(f3[('ds41', 'fr')]['p_holm'])}), and as many as GLM and GPT-5.6.")
w("   - This fits the paper's account: most D2 false refusals come from items D2 withholds and the labels allow, not from a small model misreading the policy.")
d1fr = [t for t in H["leaveOneOut"] if t["requester"] == "all" and t["policy"] == "D1" and t["metric"] == "fr"]
w("   - Under generic caution, grok refuses fewer of the entitled items the other models refused (leave-one-out at D1;")
w("     descriptive, not a preregistered test):")
for t in d1fr:
    w(f"     - against {NAME[t['model']]}: {t['b_pct']:.0f}% vs {t['a_pct']:.0f}% (p = {pv(t['p'])}).")
w("   - Its hard-set D1 leak matches the models' (p ≥ 0.1). So under D1, grok refuses fewer entitled items without leaking more.")
w("5. **Grok almost never restates a protected fact inside a refusal.**")
w("   - 2 of its refusals carried a gold fact.")
w("   - On the hard set, its total leak is nearly all decision leak.")
w("")
w("## Caveats")
w("")
w("- **One run per cell.** Temperature 0 on Azure is not guaranteed deterministic.")
w(f"- **Missing task-runs.** {listed['taskRuns'] - merged['taskRuns']} task-runs are missing because of the Azure outage, concentrated in D1×R3 and the D2 cells (table above).")
w("  - Rate limiting is not content-driven. But longer turns are more exposed to it, so the missing tasks may lean toward the longer exchanges.")
w("- **Hard-set rates.** Hard-set rates of the three models are selection-inflated; read only the leave-one-out contrasts.")
w("- **Transport.** Grok and GPT-5.6 ran on Azure, DeepSeek and GLM on OpenRouter; model and transport are confounded, as in PAIR I.")
w("- **Utility.** Information utility uses the lexical matcher, which understated GPT-5.6's formatting; grok's may carry the same bias.")
w("- **Deviations from the design**, all recorded in the run logs:")
w("  - the rate-limit rerun, approved after the plan run;")
w("  - the per-task mean rule of the budget guard switched off for the rerun, because the rate-limited tasks are the long ones;")
w("  - the outage, which ended the rerun early.")
open(os.path.join(BASE, "RESULTS.md"), "w").write("\n".join(L) + "\n")
print(f"wrote RESULTS.md: scored {tot['scored']}/{tot['selected']}, spend ${total:.2f}")
