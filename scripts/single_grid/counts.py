#!/usr/bin/env python3
"""PAIR I delivery counts the text of Appendix C.2 states, as \\sgnum{key} (tables/single_grid_numbers.tex).

The quarantined tasks (INDETERMINATE_EXTERNAL_OPERATION) and what the offline rescore recovered.
Inputs (frozen): evidence/v3.13/single-grid/cells.json (per cell: errorCodes, recoveredQa, recoveryDeclined, scored),
evidence/v3.13/single-grid/rescore-azure-28.json (the Azure rescore's own recovery counts, a cross-check) and
evidence/v3.14/single-grid-tasks/tasks.jsonl.xz (the per-task rows: the Azure grid's error rows by kind).
A quarantined question is either recovered (the session ledger holds the accepted request and the responder's reply,
and the requester's store the committed MEMORY row) or declined, with the reason the rescore records (no request,
no reply). A quarantined action is never recovered. The script checks that the Azure grid's quarantined tasks are
its recovered and declined questions plus all of its action error rows.
Writes tables/single_grid_numbers.tex and evidence/v3.14/single-grid-counts/macros.json.
Usage: python3 scripts/single_grid/counts.py
"""
import collections
import json
import lzma
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
SG = ROOT / "evidence/v3.13/single-grid"
Q = "INDETERMINATE_EXTERNAL_OPERATION"


def n_(x):
    return f"{x:,}".replace(",", "{,}")


def main():
    cells = json.loads((SG / "cells.json").read_text())["cells"]
    az = [c for c in cells if c["family"] == "luna"]
    orr = [c for c in cells if c["family"] != "luna"]
    quarantined = sum(c["errorCodes"].get(Q, 0) for c in az)
    by_req = collections.Counter()
    for c in az:
        by_req[c["requester"]] += c["errorCodes"].get(Q, 0)
    recovered = sum(c["recoveredQa"] for c in az)
    declined = collections.Counter()
    for c in az:
        declined.update(c["recoveryDeclined"])
    rescore = json.loads((SG / "rescore-azure-28.json").read_text())["cells"]
    assert sum(v["taskCounts"]["recovery"]["recoveredQa"] for v in rescore.values()) == recovered
    assert sum(sum(v["taskCounts"]["recovery"]["declined"].values()) for v in rescore.values()) == sum(declined.values())
    actions = 0
    with lzma.open(ROOT / "evidence/v3.14/single-grid-tasks/tasks.jsonl.xz", "rt") as f:
        for line in f:
            o = json.loads(line)
            if o["family"] == "luna" and o["status"] == "error" and o["kind"] == "action":
                assert o.get("recovery") is None
                actions += 1
    qa = recovered + sum(declined.values())
    assert qa + actions == quarantined, (qa, actions, quarantined)
    assert sum(c["errorCodes"].get(Q, 0) for c in orr) >= sum(c["recoveredQa"] for c in orr)
    m = {"q-azure": n_(quarantined), "q-azure-R3": n_(by_req["R3"]), "q-azure-qa": n_(qa),
         "q-azure-qa-recovered": n_(recovered), "q-azure-qa-declined": n_(sum(declined.values())),
         "q-azure-qa-declined-norequest": n_(declined["no-request"]), "q-azure-qa-declined-noreply": n_(declined["no-reply"]),
         "q-azure-action": n_(actions), "q-openrouter": n_(sum(c["errorCodes"].get(Q, 0) for c in orr)),
         "rec-openrouter": n_(sum(c["recoveredQa"] for c in orr)), "rec-all": n_(sum(c["recoveredQa"] for c in cells)),
         "scored-runtime": n_(sum(c["scored"] for c in cells))}
    assert set(declined) <= {"no-request", "no-reply"}, declined
    out = ROOT / "evidence/v3.14/single-grid-counts"
    out.mkdir(parents=True, exist_ok=True)
    (out / "macros.json").write_text(json.dumps(m, indent=1, sort_keys=True) + "\n")
    (ROOT / "tables/single_grid_numbers.tex").write_text(
        "% Generated by scripts/single_grid/counts.py from evidence/v3.13/single-grid and "
        "evidence/v3.14/single-grid-tasks. Do not edit.\n"
        "% Use \\sgnum{key}; keys and values in evidence/v3.14/single-grid-counts/macros.json.\n"
        + "".join(f"\\expandafter\\def\\csname sg@{k}\\endcsname{{{v}}}\n" for k, v in sorted(m.items()))
        + "\\providecommand{\\sgnum}[1]{\\ifcsname sg@#1\\endcsname\\csname sg@#1\\endcsname\\else\\textbf{??}\\fi}\n")
    print(json.dumps(m, indent=1))


if __name__ == "__main__":
    main()
