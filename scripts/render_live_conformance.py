#!/usr/bin/env python3
"""Render the live conformance table from the two frozen live artifacts.

The table concatenates one native run (Adversary and the model-driven Standard
column) with one MCP run (Adversary and the four installed vendor CLIs). The
concatenation is valid only while both artifacts carry the same case-set hash,
world-set hash and judge version, and the Adversary column is identical in
both; every one of those conditions is asserted here. This script executes no
conformance test and calls no model.
"""
from collections import Counter
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIVE = ROOT / 'evidence/live_conformance'
NATIVE = LIVE / 'native-conformance-2026-09-08-stack64-r1.json'
MCP = LIVE / 'mcp-conformance-2026-09-08-stack64-r1.json'
SCRIPTED = ROOT / 'evidence/kernel_conformance.source.json'
OUT = ROOT / 'tables/conformance.tex'

DIGESTS = {
    NATIVE.name: '7d9f73904ed5e0dd049af7aa3713e37b17d6c6be063ec298f214943ad368c629',
    MCP.name: 'ba6950641d7e473222b8f9b25200b13f93efb844782f11c48bce5dd82ad26bef',
}

# (artifact, column id, printed label)
COLUMNS = [
    ('native', 'adversary-embedded', 'Adversary'),
    ('native', 'model-live', 'Standard (live model)'),
    ('mcp', 'codex-mcp', 'Codex'),
    ('mcp', 'claude-code-mcp', 'Claude Code'),
    ('mcp', 'deepseek-mcp', 'DeepSeek'),
    ('mcp', 'pi-mcp', 'Pi'),
]
STATUSES = ['pass', 'not_applicable', 'out_of_scope', 'not_exercised', 'not_implemented']


def load(path):
    data = path.read_bytes()
    assert hashlib.sha256(data).hexdigest() == DIGESTS[path.name], path.name
    return json.loads(data)


def column(artifact, cid):
    rows = artifact['manifest']['rows']
    return [next(c for c in r['cells'] if c['columnId'] == cid) for r in rows]


def main():
    native, mcp, scripted = load(NATIVE), load(MCP), json.loads(SCRIPTED.read_text())
    for a in (native, mcp):
        m = a['manifest']
        assert m['caseSetHash'] == scripted['caseSetHash']
        assert m['worldSetHash'] == scripted['worldSetHash']
        assert m['judgeVersion'] == scripted['judgeVersion'] == '4'
        assert len(m['rows']) == 32 and len({r['caseId'] for r in m['rows']}) == 29
        assert len(a['casesRun']) == 29
    assert [r['caseId'] for r in native['manifest']['rows']] == [r['caseId'] for r in mcp['manifest']['rows']]
    assert column(native, 'adversary-embedded') == column(mcp, 'adversary-embedded')
    assert mcp['sharedOs']['version'] == '0.1.0-alpha.4'
    assert all(a['available'] for a in mcp['availability'])
    assert {a['model']['id'] for a in mcp['availability']} == {'deepseek-v4-flash'}
    assert native['availability'][0]['detail']['model'] == 'deepseek-v4-flash'
    assert native['availability'][0]['detail']['thinking'] == 'disabled'
    # The live Standard column was asked the same prompts as the scripted one.
    live_std = next(c for c in native['manifest']['columns'] if c['id'] == 'model-live')
    scripted_std = next(c for c in scripted['columns'] if c['id'] == 'model-scripted')
    assert live_std['promptSetHash'] == scripted_std['promptSetHash']

    calls = {c['columnId']: len(c['calls']) for c in mcp['catalogues']}
    # The native artifact records no catalogue; its call counts come from its log.
    calls['model-live'] = 78
    assert calls['adversary-embedded'] == 80

    lines = []
    totals = Counter()
    total_attempts = total_calls = 0
    for src, cid, label in COLUMNS:
        cells = column(native if src == 'native' else mcp, cid)
        st = Counter(c['status'] for c in cells)
        assert set(st) <= set(STATUSES), (cid, st)
        assert all(c['recordGaps'] == [] for c in cells)
        attempts = sum(c['attempted'] for c in cells)
        driver = sum(1 for c in cells if c['driverIssued'])
        assert driver == (1 if cid == 'model-live' else 0)
        counts = [st[s] for s in STATUSES]
        lines.append(f"{label} & " + ' & '.join(str(n) for n in counts) + f" & {attempts} & {calls[cid]} \\\\")
        totals += st
        total_attempts += attempts
        total_calls += calls[cid]
    assert totals == Counter({'pass': 139, 'not_applicable': 35, 'out_of_scope': 4,
                              'not_exercised': 2, 'not_implemented': 12}), totals
    assert total_attempts == 413 and total_calls == 446
    body = '\n'.join(lines)
    tex = r'''% Generated by scripts/render_live_conformance.py from evidence/live_conformance/.
\begin{table}[ht]
\centering
\caption{\textbf{Live conformance, one pass.} The 29 cases and 32 rows of the scripted matrix (Table~\ref{tab:infra-cases}), with identical case-set, world-set and judge hashes, run on 8 September 2026 at the pinned revision with \texttt{deepseek-v4-flash} driving the Standard loop (thinking off) and the four CLIs. The Standard column runs the live model inside the \SharedOS{} loop; the Codex, Claude Code, DeepSeek and Pi CLIs run their own loops on the permission-filtered catalog served over MCP (Pi is a coding-agent CLI). NA: the harness structurally cannot make the attempt; OOS: declared out of scope once the CLI owns the loop (the step-ceiling row); NE: the control attempt was never delivered, so the row proves nothing; NI: not implemented. Attempts are declared attempts issued; calls are all mediated operations recorded. The Standard pass count includes one driver-issued step-ceiling test. No cell fails.}
\label{tab:conformance}
\small
\setlength{\tabcolsep}{4pt}
\begin{tabular}{@{}lrrrrrrr@{}}
\toprule
Column & Pass & NA & OOS & NE & NI & Attempts & Calls \\
\midrule
''' + body + r'''
\midrule
Total & ''' + ' & '.join(str(totals[s]) for s in STATUSES) + f" & {total_attempts} & {total_calls}" + r''' \\
\bottomrule
\end{tabular}
\end{table}
'''
    OUT.write_text(tex)
    print(f'wrote {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
