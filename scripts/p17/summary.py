#!/usr/bin/env python3
"""Readable summary of the total-leak and corrected-inference outputs (no new computation).

Reads evidence/v3.14/p17/{pair1_tests,pair2_tests,families}.json and writes
evidence/v3.14/p17/summary.md: each family test with its rates, discordant counts, p, Holm-adjusted p,
interval and wording; each leak contrast split into its decision and refusal-channel parts.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts" / "common"))
from fractions import Fraction

from halfup import fixed, fmt_p, to_fraction  # noqa: E402

P = ROOT / "evidence/v3.14/p17"
t1 = json.loads((P / "pair1_tests.json").read_text())
t2 = json.loads((P / "pair2_tests.json").read_text())
fam = json.loads((P / "families.json").read_text())


def pp(x):
    """A share or difference, scaled after it is read exactly: every stored value is one division (a count over n,
    or a bootstrap sum over its n), so repr recovers it; 100 * 0.6325 would be 63.24999999999999."""
    return fixed(100 * to_fraction(x), 1)


def comp(x):
    """100 minus a share, from the exact share."""
    return fixed(100 * (1 - to_fraction(x)), 1)


def neg(x):
    return fixed(-100 * to_fraction(x), 1)


def rc_part(v, d):
    """The refusal-channel part of a total-leak difference: (TD - DL) differences, from both tests' counts."""
    assert v["n"] == d["n"]
    (a10, a01), (b10, b01) = v["improved_worsened"], d["improved_worsened"]
    return fixed(Fraction(100 * ((a01 - a10) - (b01 - b10)), v["n"]), 1)


lines = ["# Total leak and corrected inference: summary (generated by scripts/p17/summary.py)", "",
         "## PAIR I primary family (Holm over 48; leak = total disclosure)", "",
         "| Test | rate a → b (%) | improved:worsened | p | Holm p | 95% CI of b − a (pts) | DL part | RC part |",
         "|---|---|---|---|---|---|---|---|"]
for k in sorted(fam["pair1_family"], key=lambda k: (t1[k]["metric"], t1[k]["contrast"], k)):
    v, h = t1[k], fam["pair1_family"][k]
    dl = rc = ""
    if v["metric"] == "leak_TD":
        d = t1[k.replace("leak_TD", "leak_DL")]
        dl = pp(d["diff"])
        rc = rc_part(v, d)
    lines.append(f"| {k} | {pp(v['rate_a'])} → {pp(v['rate_b'])} | {v['improved_worsened'][0]}:{v['improved_worsened'][1]} "
                 f"| {fmt_p(v['p'])} | {fmt_p(h['holm'])} | [{pp(v['ci'][0])}, {pp(v['ci'][1])}] | {dl} | {rc} |")
lines += ["", "## PAIR II primary family (Holm over 36; group sign-flip; leak = total disclosure)", "",
          "| Test | rate a → b (%) | improved:worsened | non-zero groups | floor | p | Holm p | group-bootstrap 95% CI (pts) |",
          "|---|---|---|---|---|---|---|---|"]
for k in sorted(fam["pair2_family"], key=lambda k: (t2[k]["metric"], t2[k]["contrast"], k)):
    v, h = t2[k], fam["pair2_family"][k]
    lines.append(f"| {k} | {pp(v['rate_a'])} → {pp(v['rate_b'])} | {v['improved_worsened'][0]}:{v['improved_worsened'][1]} "
                 f"| {v['nonzero_groups']} | {fmt_p(v['floor'])} | {fmt_p(v['signflip_p'])} | {fmt_p(h['holm'])} "
                 f"| [{pp(v['group_bootstrap_ci'][0])}, {pp(v['group_bootstrap_ci'][1])}] |")
lines += ["", "## PAIR II pooled over the nine blocks (group bootstrap)", "",
          "| Test | rate a → b (%) | b − a (pts) | 95% CI | wording |", "|---|---|---|---|---|"]
for k, v in t2.items():
    if k.startswith("pooled"):
        lines.append(f"| {k} | {pp(v['rate_a'])} → {pp(v['rate_b'])} | {pp(v['diff'])} "
                     f"| [{pp(v['group_bootstrap_ci'][0])}, {pp(v['group_bootstrap_ci'][1])}] | {v['null_reading']} |")
for group, title in (("swap_harness_leak_FR", "Table 24: requester swaps and harness, leak (total) and FR"),
                     ("swap_harness_AU_AS", "Requester swaps and harness, action utility and action safety")):
    q = fam["pair1_bh"][group]["q"]
    lines += ["", f"## PAIR I {title} (Benjamini-Hochberg within the table, {len(q)} tests)", ""]
    if group == "swap_harness_AU_AS":
        lines += ["Action utility and action safety are printed as rates of success (higher is better); the test",
                  "counts failures, so improved:worsened is gained:lost.", ""]
    lines += ["| Test | rate a → b (%) | improved:worsened | b − a (pts) | 95% CI | p | q | wording |",
              "|---|---|---|---|---|---|---|---|"]
    for k in sorted(q, key=lambda k: (t1[k]["metric"], k)):
        v = t1[k]
        if v["metric"] in ("AU", "AS"):
            lines.append(f"| {k} | {comp(v['rate_a'])} → {comp(v['rate_b'])} | {v['improved_worsened'][0]}:{v['improved_worsened'][1]} "
                         f"| {neg(v['diff'])} | [{neg(v['ci'][1])}, {neg(v['ci'][0])}] "
                         f"| {fmt_p(v['p'])} | {fmt_p(q[k])} | {v['null_reading']} |")
            continue
        lines.append(f"| {k} | {pp(v['rate_a'])} → {pp(v['rate_b'])} | {v['improved_worsened'][0]}:{v['improved_worsened'][1]} "
                     f"| {pp(v['diff'])} | [{pp(v['ci'][0])}, {pp(v['ci'][1])}] "
                     f"| {fmt_p(v['p'])} | {fmt_p(q[k])} | {v['null_reading']} |")
q = fam["pair2_bh"]["utility_D0D2"]["q"]
lines += ["", "## PAIR II ladder grid, utility D0 → D2 per block (Table 27; group sign-flip; BH over the nine blocks)", "",
          "| Test | U at D0 → D2 (%) | gained:lost | non-zero groups | sign-flip p | task McNemar p | q |",
          "|---|---|---|---|---|---|---|"]
for k in sorted(q):
    v = t2[k]
    lines.append(f"| {k} | {comp(v['rate_a'])} → {comp(v['rate_b'])} | {v['improved_worsened'][0]}:{v['improved_worsened'][1]} "
                 f"| {v['nonzero_groups']} | {fmt_p(v['signflip_p'])} | {fmt_p(v['task_mcnemar_p'])} | {fmt_p(q[k])} |")
fs = json.loads((P / "pair2_filter_sensitivity.json").read_text())
lines += ["", f"## PAIR II filter sensitivity: the {fs['touched_tasks']} filter-touched tasks removed (Holm over 36 again)", "",
          "| Test | improved:worsened | non-zero groups | sign-flip p | Holm p | Holm p, all tasks | verdict changes |",
          "|---|---|---|---|---|---|---|"]
for k, v in fs["tests"].items():
    lines.append(f"| {k} | {v['improved_worsened'][0]}:{v['improved_worsened'][1]} | {v['nonzero_groups']} | {fmt_p(v['signflip_p'])} "
                 f"| {fmt_p(v['holm'])} | {fmt_p(v['holm_all_tasks'])} | {'yes' if v['verdict_changes'] else 'no'} |")
lines += ["", "## Decision-leak sensitivity families (Holm, the same tests with decision leak in place of total leak)", ""]
for fam_key, label in (("pair1_family_DL", "PAIR I"), ("pair2_family_DL", "PAIR II")):
    f = fam[fam_key]
    sig_td = {k for k, v in fam[fam_key.replace("_DL", "")].items() if v["holm"] < 0.05}
    sig_dl = {k for k, v in f.items() if v["holm"] < 0.05}
    lines.append(f"- {label}: {len(sig_dl)} of {len(f)} significant after Holm with decision leak "
                 f"({len(sig_td)} of {len(f)} with total leak).")
(P / "summary.md").write_text("\n".join(lines) + "\n")
print("wrote", (P / "summary.md").relative_to(ROOT))
